-- STAR-X TECHNOLOGIES: starter Supabase schema
-- Run this whole file in Supabase Dashboard > SQL Editor > New query.
-- This starter intentionally allows public product viewing and public enquiry submission,
-- but does NOT allow public reads of customer enquiries or public product editing.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Software',
  description text not null default '',
  price_mwk numeric(12,2),
  image_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_email text not null,
  service text not null,
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.enquiries enable row level security;

drop policy if exists "Public can view active products" on public.products;
create policy "Public can view active products"
on public.products for select
to anon, authenticated
using (is_active = true);

drop policy if exists "Visitors can submit enquiries" on public.enquiries;
create policy "Visitors can submit enquiries"
on public.enquiries for insert
to anon, authenticated
with check (
  length(trim(customer_name)) between 1 and 100
  and length(trim(customer_email)) between 3 and 254
  and length(trim(service)) between 1 and 100
  and length(trim(message)) between 1 and 5000
);

-- No SELECT/UPDATE/DELETE policy is created for enquiries.
-- No public INSERT/UPDATE/DELETE policy is created for products.
-- Manage products and private enquiries in Supabase Dashboard for now.
